#!/usr/bin/env python3
"""Generate index-age-check.html from index.html + the age gate partial.

    index.html                the page, hand-written (single source of truth)
    partials/age-gate.html    the "Your Vintage" age gate markup + opener script
    assets/css/gate.css       age gate styles   (inlined into the gated page only)
    assets/js/gate.js         age gate behaviour (linked only from the gated page)

Output (commit it, GitHub Pages serves it as-is):
    index-age-check.html      identical to index.html plus the age gate

Run after ANY edit to index.html:   python3 tools/build.py
"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
page = (root / "index.html").read_text(encoding="utf-8")
gate = (root / "partials" / "age-gate.html").read_text(encoding="utf-8")
# gate.css is small, so it is inlined (no second render-blocking request); fix its relative paths
gate_css = (root / "assets" / "css" / "gate.css").read_text(encoding="utf-8").replace("../img/", "assets/img/").strip()

CSS = '<link rel="stylesheet" href="assets/css/site.css">'
BODY = "<body>\n"
JS = '<script src="assets/js/site.js" defer></script>'
import re
# On the gated page the doors (crest.svg) are the first thing seen, not the bottle:
# preload the crest instead of the hero image so it wins the bandwidth race.
IMG_PRELOAD = re.search(r'<link rel="preload" as="image"[^\n]*\n', page).group(0)
for hook in (CSS, BODY, JS, IMG_PRELOAD):
    assert hook in page, f"hook missing from index.html: {hook!r}"

out = (page
       .replace(IMG_PRELOAD, '<link rel="preload" as="image" type="image/svg+xml" href="assets/img/crest.svg" fetchpriority="high">\n', 1)
       .replace('alt="A bottle of Héloïse Lloris Vintage 1996, encased in hammered 24K gold" fetchpriority="high"', 'alt="A bottle of Héloïse Lloris Vintage 1996, encased in hammered 24K gold"', 1)
       # hero bottle is hidden behind the doors: gate.js gives it its srcset when the case opens
       .replace('<img src="assets/img/bottle-gold-420.webp" srcset=', '<img data-gate-srcset=', 1)
       .replace(CSS, CSS + "\n<style>\n" + gate_css + "\n</style>", 1)
       .replace(BODY, BODY + gate, 1)
       .replace(JS, JS + '\n<script src="assets/js/gate.js" defer></script>', 1)
       .replace("<!doctype html>", "<!doctype html>\n<!-- GENERATED by tools/build.py from index.html + partials/age-gate.html. Edit those, then re-run. -->", 1))
(root / "index-age-check.html").write_text(out, encoding="utf-8")
print("built index-age-check.html")
